/* Strongback September 2026 cleanup + rollback + Williams Brothers alias fix — the committed SQL files run in a
   REAL Postgres (uuid ids, as production) with MI-1a Parts 0–2 installed (write guard on) and pg-safeupdate loaded
   on every session (fixture). The ids and preview fingerprint are production's; the test plants rows with those
   ids and substitutes only the fingerprint this database computes, so what is tested is what Angelo runs.
     PGTEST_PSQL=/usr/lib/postgresql/16/bin/psql PGHOST=/var/tmp/pgmi PGPORT=55433 PGUSER=postgres node test/commission-sept2026.pg.test.js */
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const assert = require('assert');

const PSQL = process.env.PGTEST_PSQL || 'psql';
const SUP = f => path.join(__dirname, '..', 'supabase', f);
const FIX = path.join(__dirname, 'mi1a', 'fixture.sql');
const run = (db, sql, role) => { const args = ['-X', '-q', '-A', '-t', '-v', 'ON_ERROR_STOP=1', '-d', db, '-c', role ? `set role ${role}; ${sql}` : sql];
  const r = spawnSync(PSQL, args, { encoding: 'utf8' });
  if (r.error || r.status !== 0) throw new Error((r.error && r.error.message) || r.stderr || ('psql exit ' + r.status)); return r.stdout.trim(); };
const fileRaw = (db, f) => spawnSync(PSQL, ['-X', '-q', '-v', 'ON_ERROR_STOP=1', '-d', db, '-f', f], { encoding: 'utf8' });
const file = (db, f) => { const r = fileRaw(db, f); if (r.status !== 0) throw new Error(r.stderr); return r; };
try { run('postgres', 'select 1'); } catch (e) { console.log('SKIP: no Postgres (' + String(e.message).split('\n')[0] + ')'); process.exit(0); }

let pass = 0, fail = 0;
function t(name, fn) { try { fn(); pass++; console.log('  ok   ' + name); } catch (e) { fail++; console.log('  FAIL ' + name + '\n       ' + (e && e.message || e).toString().split('\n')[0]); } }
const tmp = (name, text) => { const p = path.join(require('os').tmpdir(), 'sep26-' + process.pid + '-' + name + '.sql'); fs.writeFileSync(p, text); return p; };
const PROD_FP = 'c7b81f69492ca44fb229a3d757cdc015';
const IDS = ['3e58af95-bf1b-4510-a35a-dc4b3bf8f2bb', '5f214540-71ab-4f29-a5f1-6247dda3192f', '5ffe8cd4-fa59-48ee-88a7-5f035e158cd5',
  '7e90d782-5cbc-42c8-a20b-0534f1338c5e', '842c2dc5-b219-481e-ac0c-e7ee0bc00f5d', 'b01196d7-90f5-4ade-9283-e94fb493943a', 'c7158ea2-d2da-42ef-a0bf-24361ebdcbc3'];
const HQ = '86baecc2-448f-4759-988d-bdc01c5123e6', PRI = '3396b841-f1f3-41a3-9255-f9d880479f1d';
const FPQ = `select md5(string_agg(to_jsonb(m)::text, '|' order by m.id::text)) from monthly_sales m where m.id::text in (${IDS.map(i => `'${i}'`).join(',')})`;
const TOT = `select count(*)||'/'||coalesce(sum(amount),0)||'/'||coalesce(sum(commission),0) from monthly_sales`;
const OTHERS = `select md5(string_agg(to_jsonb(m)::text, '|' order by m.id::text)) from monthly_sales m where m.id::text not in (${IDS.map(i => `'${i}'`).join(',')})`;

function fresh(db) {
  run('postgres', `drop database if exists ${db}`); run('postgres', `create database ${db}`);
  file(db, tmp('fx', fs.readFileSync(FIX, 'utf8').replace('id bigint generated by default as identity primary key,', 'id uuid primary key default gen_random_uuid(),')));
  for (const s of ['mi1a_part0_snapshot.sql', 'mi1a_part1_schema.sql', 'mi1a_part2_rekey_strongback.sql']) file(db, SUP(s));
  run(db, `create table dealer_aliases(alias_norm text primary key, raw_name text, dealer_id uuid, created_at timestamptz default now());
    insert into dealers(id,business_name,city,state,zip) values ('${HQ}','Williams Brothers Washington HQ (prod id)','Washington','IN','47501');
    insert into dealers(id,business_name,parent_id,city,state,zip) values ('${PRI}','Williams Brothers Princeton','${HQ}','Princeton','IN','47670');
    insert into dealer_aliases(alias_norm,raw_name,dealer_id) values ('WILLIAMS BROTHERS HEALTHCARE PHARMACY','Williams Brothers Healthcare Pharmacy','${PRI}');`);
  const vals = IDS.map((id, i) => `('${id}','strongback-mobility','2026-09-01','commission','Strongback Sept Commission Report 2026.csv','2026-10-10 23:49:18.914+00',${i % 3 ? 1 : 25},'cust ${i}','4767${i}')`).join(',');
  run(db, `insert into monthly_sales(id,manufacturer,period,source,source_file,imported_at,qty,customer_name,ship_zip) values ${vals};
    insert into monthly_sales(manufacturer,period,source,source_file,amount,commission,customer_name) values ('pedifix','2026-09-01','commission','pf.csv',100,10,'Other dealer');`);
  return run(db, FPQ);
}
const withFp = (fp, f) => tmp(path.basename(f), fs.readFileSync(SUP(f), 'utf8').split(PROD_FP).join(fp));

const DB = 'sep26_' + process.pid;
console.log('\n— Strongback September 2026 cleanup —');

t('the committed cleanup quarantines exactly the 7 rows, whole, and nothing else moves', () => {
  const fp = fresh(DB); const before = run(DB, TOT), others = run(DB, OTHERS);
  file(DB, withFp(fp, 'commission_sept2026_cleanup.sql'));
  assert.strictEqual(run(DB, `select count(*) from monthly_sales where manufacturer='strongback-mobility' and period='2026-09-01'`), '0');
  assert.strictEqual(run(DB, `select count(*) from monthly_sales_quarantine where restored_at is null and reason='strongback_2026_09_blank_commission_rows'`), '7');
  const [n, s, c] = before.split('/'); assert.strictEqual(run(DB, TOT), `${n - 7}/${s}/${c}`);
  assert.strictEqual(run(DB, OTHERS), others, 'every other row untouched');
  assert.strictEqual(run(DB, `select string_agg(sales_row_id, ',' order by sales_row_id) from monthly_sales_quarantine`), IDS.slice().sort().join(','));
  assert.strictEqual(run(DB, `select count(*) from monthly_sales_quarantine where row_fp = md5(row_data::text) and row_data->>'source_file' = 'Strongback Sept Commission Report 2026.csv'`), '7');
  assert.ok(/Angelo Audia, 2026-10-10/.test(run(DB, `select evidence->>'decision' from monthly_sales_quarantine limit 1`)));
});
t('the quarantine is closed to ordinary users (RULE 19) and open to service_role', () => {
  for (const role of ['anon', 'authenticated']) {
    assert.throws(() => run(DB, 'select count(*) from monthly_sales_quarantine', role), /permission denied/);
    assert.strictEqual(run(DB, `select has_table_privilege('${role}','monthly_sales_quarantine','select')`), 'f');
  }
  assert.strictEqual(run(DB, 'select count(*) from monthly_sales_quarantine', 'service_role'), '7');
  assert.strictEqual(run(DB, `select relrowsecurity from pg_class where relname='monthly_sales_quarantine'`), 't');
});
t('running the cleanup a second time is refused and writes nothing', () => {
  const fp = run(DB, `select md5(string_agg(row_data::text, '|' order by sales_row_id)) from monthly_sales_quarantine`);
  const before = run(DB, TOT);
  const r = fileRaw(DB, withFp(fp, 'commission_sept2026_cleanup.sql'));
  assert.notStrictEqual(r.status, 0); assert.ok(/expected exactly 7 matching rows, found 0/.test(r.stderr), r.stderr);
  assert.strictEqual(run(DB, TOT), before); assert.strictEqual(run(DB, 'select count(*) from monthly_sales_quarantine'), '7');
});
t('the rollback restores the 7 rows byte-identical (same ids, preview fingerprint) and keeps the history', () => {
  const fp = run(DB, `select md5(string_agg(row_data::text, '|' order by sales_row_id)) from monthly_sales_quarantine`);
  const before = run(DB, TOT);
  file(DB, withFp(fp, 'commission_sept2026_cleanup_rollback.sql'));
  assert.strictEqual(run(DB, FPQ), fp);
  const [n, s, c] = before.split('/'); assert.strictEqual(run(DB, TOT), `${+n + 7}/${s}/${c}`);
  assert.strictEqual(run(DB, `select count(*) from monthly_sales_quarantine where restored_at is not null`), '7');
});
t('the rollback run twice is refused; the cleanup can be run again after a rollback', () => {
  const fp = run(DB, FPQ);
  const r = fileRaw(DB, withFp(fp, 'commission_sept2026_cleanup_rollback.sql'));
  assert.notStrictEqual(r.status, 0); assert.ok(/expected 7 quarantined rows to restore, found 0/.test(r.stderr), r.stderr);
  file(DB, withFp(fp, 'commission_sept2026_cleanup.sql'));
  assert.strictEqual(run(DB, `select count(*) from monthly_sales_quarantine where restored_at is null`), '7');
  assert.strictEqual(run(DB, `select count(*) from monthly_sales_quarantine`), '14');
});
t('a row changed since the preview stops the cleanup (fingerprint) — nothing written', () => {
  const fp = fresh(DB); run(DB, `update monthly_sales set qty = 99 where id = '${IDS[0]}'`);
  const before = run(DB, TOT);
  const r = fileRaw(DB, withFp(fp, 'commission_sept2026_cleanup.sql'));
  assert.notStrictEqual(r.status, 0); assert.ok(/changed since the preview/.test(r.stderr), r.stderr);
  assert.strictEqual(run(DB, TOT), before);
  assert.strictEqual(run(DB, `select count(*) from pg_class where relname='monthly_sales_quarantine'`), '0', 'the whole transaction rolled back');
});
t('a row that gained an amount is no longer a blank row and stops the cleanup', () => {
  const fp = fresh(DB); run(DB, `update monthly_sales set amount = 10 where id = '${IDS[1]}'`);
  const r = fileRaw(DB, withFp(fp, 'commission_sept2026_cleanup.sql'));
  assert.notStrictEqual(r.status, 0); assert.ok(/expected exactly 7 matching rows, found 6/.test(r.stderr), r.stderr);
});
t('another Strongback September commission row (e.g. a real statement loaded meanwhile) stops the cleanup', () => {
  const fp = fresh(DB);
  run(DB, `insert into monthly_sales(manufacturer,period,source,source_file,amount,commission) values ('strongback-mobility','2026-09-01','commission','real.xlsx',2159,194.31)`);
  const r = fileRaw(DB, withFp(fp, 'commission_sept2026_cleanup.sql'));
  assert.notStrictEqual(r.status, 0); assert.ok(/other Strongback September commission rows exist/.test(r.stderr), r.stderr);
});
t('the committed cleanup file carries the production fingerprint and ids, and every UPDATE/DELETE has a WHERE', () => {
  for (const f of ['commission_sept2026_cleanup.sql', 'commission_sept2026_cleanup_rollback.sql', 'williams_brothers_alias_fix.sql', 'williams_brothers_alias_fix_rollback.sql']) {
    const sql = fs.readFileSync(SUP(f), 'utf8').replace(/--.*$/gm, '');
    for (const stmt of sql.split(';')) if (/^\s*(update|delete)\b/im.test(stmt)) assert.ok(/\bwhere\b/i.test(stmt), f + ': ' + stmt.trim().slice(0, 60));
  }
  const c = fs.readFileSync(SUP('commission_sept2026_cleanup.sql'), 'utf8');
  assert.ok(c.includes(PROD_FP)); for (const id of IDS) assert.ok(c.includes(id), id);
});

console.log('\n— Williams Brothers alias —');
t('the alias fix moves the generic name from Princeton to the HQ, and only that row', () => {
  fresh(DB); const before = run(DB, `select count(*)||md5(string_agg(alias_norm||dealer_id, ',' order by alias_norm)) from dealer_aliases where alias_norm <> 'WILLIAMS BROTHERS HEALTHCARE PHARMACY'`);
  const ms = run(DB, TOT);
  file(DB, SUP('williams_brothers_alias_fix.sql'));
  assert.strictEqual(run(DB, `select dealer_id from dealer_aliases where alias_norm='WILLIAMS BROTHERS HEALTHCARE PHARMACY'`), HQ);
  assert.strictEqual(run(DB, `select count(*)||md5(string_agg(alias_norm||dealer_id, ',' order by alias_norm)) from dealer_aliases where alias_norm <> 'WILLIAMS BROTHERS HEALTHCARE PHARMACY'`), before);
  assert.strictEqual(run(DB, TOT), ms);
});
t('run again it is refused; the rollback puts it back on Princeton', () => {
  const r = fileRaw(DB, SUP('williams_brothers_alias_fix.sql'));
  assert.notStrictEqual(r.status, 0); assert.ok(/not \(or no longer\) on Princeton/.test(r.stderr), r.stderr);
  file(DB, SUP('williams_brothers_alias_fix_rollback.sql'));
  assert.strictEqual(run(DB, `select dealer_id from dealer_aliases where alias_norm='WILLIAMS BROTHERS HEALTHCARE PHARMACY'`), PRI);
});

run('postgres', `drop database if exists ${DB}`);
console.log(`\ncommission-sept2026 (Postgres): ${pass} passed, ${fail} failed`);
process.exitCode = fail ? 1 : 0;
